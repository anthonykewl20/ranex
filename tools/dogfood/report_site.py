"""Public benchmark page for ranex, written for a NON-technical reader.

Every number is real and generated by code anyone can run — but it is always
presented next to a human-scale comparison (a camera flash, an eye-blink, a
heartbeat) and in everyday words. No kernel vocabulary anywhere on the page.

One self-contained HTML file: inline SVG charts, no external JS/CSS/fonts or
network calls. The fingerprint (sha256) of the raw data file is printed on
the page so the page and the data can be checked against each other.
"""

