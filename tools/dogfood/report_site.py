# Human time anchors used across the page (stated on the page itself).
# camera flash ≈ 1 ms · eye-blink ≈ 300 ms · heartbeat ≈ 1 s
def human_time(ms: float) -> str:
    if ms < 1:
        return "faster than a camera flash"
    if ms < 40:
        return "a tiny sliver of an eye-blink"
    if ms < 150:
        return "about a third of an eye-blink"
    if ms < 450:
        return "about one eye-blink"
    if ms < 1400:
        return "under one heartbeat"
    if ms < 3000:
        return "about one heartbeat"
    return "a couple of heartbeats"


